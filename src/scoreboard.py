"""Write SCOREBOARD.md: every live forecast that has an actual, model against persistence.

Misses are listed the same way as wins. The numbers come from the forecast log
(logs/predictions.csv, restored into DuckDB) and the daily actuals from ingest.
"""
import json
import sys

import duckdb
import pandas as pd

from data import load_clean
from evaluate_live import evaluate

# These forecasts were made about 23:00 on their own target day, so they were not ahead of time.
LATE_DAYS = {"2026-10-16"}
OUT = "SCOREBOARD.md"


def score(pred, actual):
    """Join forecasts to actuals and compute absolute errors for model and persistence."""
    pred = pred.copy()
    pred["forecast_for"] = pd.to_datetime(pred["forecast_for"])
    a = actual.rename(columns={"day": "forecast_for", "pm25": "actual"})
    m = pred.merge(a, on=["location_name", "forecast_for"], how="inner")
    m["model_err"] = (m["actual"] - m["pred"]).abs()
    m["persist_err"] = (m["actual"] - m["persist"]).abs()
    return m.sort_values(["forecast_for", "location_name"]).reset_index(drop=True)


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def _closer(r):
    if r["model_err"] < r["persist_err"]:
        return "model"
    if r["model_err"] > r["persist_err"]:
        return "persistence"
    return "tie"


def _group_rows(m, key):
    rows = []
    for k, g in m.groupby(key, sort=True):
        label = k.date() if hasattr(k, "date") else k
        rows.append((label, len(g), f"{g['model_err'].mean():.2f}", f"{g['persist_err'].mean():.2f}"))
    return rows


def render(m, n_logged, window_days, min_rows, pred=None, actual=None):
    L = ["# Live scoreboard", "",
         "Every logged forecast that already has an actual, model against persistence "
         "(tomorrow = today). Errors are absolute, in µg/m³. Wins and misses are listed alike. "
         "Regenerated by every daily run.", ""]
    if m.empty:
        L += [f"Forecasts logged: {n_logged}. None has an actual yet.", ""]
        return "\n".join(L)

    n = len(m)
    mm, pm = m["model_err"].mean(), m["persist_err"].mean()
    closer = m.apply(_closer, axis=1)
    L += ["## Summary", "",
          f"- Forecasts logged: {n_logged}; scored: {n}; actuals through {m['forecast_for'].max().date()}",
          f"- Model MAE: {mm:.2f}   Persistence MAE: {pm:.2f}   Difference (persistence minus model): {pm - mm:+.2f}",
          f"- Model closer on {(closer == 'model').sum()} of {n} forecasts, "
          f"persistence on {(closer == 'persistence').sum()}, ties {(closer == 'tie').sum()}"]
    if n < min_rows:
        L.append(f"- Rule 2 (trailing {window_days}-day model MAE worse than persistence) is not evaluated "
                 f"until {min_rows} forecasts are scored; {n} so far. **Too few to conclude anything.**")
    elif pred is not None:
        r = evaluate(pred, actual, window_days, min_rows)
        if r["status"] == "evaluated":
            L.append(f"- Rule 2 over the last {window_days} days (n={r['n']}, as of {r['as_of'].date()}): "
                     f"model {r['mae_model']:.2f}, persistence {r['mae_persist']:.2f}, "
                     f"**ALERT={r['alert']}**")
        else:
            L.append(f"- Rule 2: {r['message']}")
    L += ["", "## By forecast day", ""]
    L += _table(["Day", "Forecasts", "Model MAE", "Persistence MAE"], _group_rows(m, "forecast_for"))
    L += ["", "## By station", ""]
    L += _table(["Station", "Forecasts", "Model MAE", "Persistence MAE"], _group_rows(m, "location_name"))
    L += ["", "## By model version (training date)", ""]
    L += _table(["Trained through", "Forecasts", "Model MAE", "Persistence MAE"],
                _group_rows(m, "model_trained_through"))
    L += ["", "## Every scored forecast, newest first", ""]
    rows = []
    for _, r in m.sort_values(["forecast_for", "location_name"], ascending=[False, True]).iterrows():
        day = str(r["forecast_for"].date())
        flag = " †" if day in LATE_DAYS else ""
        rows.append((day + flag, r["location_name"], f"{r['pred']:.1f}", f"{r['persist']:.1f}",
                     f"{r['actual']:.1f}", f"{r['model_err']:.1f}", f"{r['persist_err']:.1f}", _closer(r)))
    L += _table(["Day", "Station", "Forecast", "Persistence", "Actual", "Model err", "Persistence err", "Closer"], rows)
    L += ["", "## Read this before drawing conclusions", "",
          "- Few forecasts, four stations that share the same weather: they are not independent samples.",
          "- † Made at about 23:00 on the target day, so not ahead of time. Kept and flagged.",
          "- Forecasts from GitHub Actions are made around midday or later on the target day, from data "
          "through the day before; part of the target day has already passed.",
          "- Actuals can be revised after a day ends. This table is rebuilt from the latest ingest.",
          "- The model changes at each weekly retrain. Each version above has scored different days, so "
          "compare a version with its own persistence column, not with another version's MAE.", ""]
    return "\n".join(L)


def main(out=OUT):
    cfg = json.load(open("config/monitor.json", encoding="utf-8"))
    con = duckdb.connect("data/pm25.duckdb", read_only=True)
    try:
        pred = con.execute("SELECT * FROM predictions").df()
    except duckdb.CatalogException:
        print("No predictions table yet.")
        return 0
    finally:
        con.close()
    actual = load_clean()
    m = score(pred, actual)
    text = render(m, len(pred), cfg.get("gt_window_days", 14), cfg.get("gt_min_rows", 28), pred, actual)
    open(out, "w", encoding="utf-8").write(text)
    print(f"wrote {out}: {len(m)} scored of {len(pred)} logged")
    return 0


if __name__ == "__main__":
    sys.exit(main())